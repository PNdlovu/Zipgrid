-- ============================================================
-- MODULE S — V2G / GRID SERVICES (SCHEDULING HOOKS)
-- Vehicle-to-Grid and smart charging export scheduling.
-- Stores scheduled grid export events triggered by tariff engine.
-- Actual V2G hardware interaction deferred to Phase 4 hardware partners.
-- ============================================================

CREATE TYPE grid_schedule_type AS ENUM (
    'smart_charge',         -- standard optimised charge (off-peak)
    'v2g_export',           -- export stored energy to grid
    'demand_response',      -- reduce charge rate on grid request
    'solar_priority'        -- charge from solar when available
);

CREATE TYPE grid_schedule_status AS ENUM (
    'scheduled',
    'executing',
    'completed',
    'cancelled',
    'failed'
);

CREATE TABLE grid_schedules (
    id                  UUID                    PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id             UUID                    NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    vehicle_id          UUID                    REFERENCES driver_vehicles(id) ON DELETE SET NULL,
    listing_id          UUID                    REFERENCES charger_listings(id) ON DELETE SET NULL,

    type                grid_schedule_type      NOT NULL DEFAULT 'smart_charge',
    status              grid_schedule_status    NOT NULL DEFAULT 'scheduled',

    -- Window
    window_start        TIMESTAMPTZ             NOT NULL,
    window_end          TIMESTAMPTZ             NOT NULL,

    -- Target parameters
    target_soc_pct      SMALLINT CHECK (target_soc_pct BETWEEN 0 AND 100),
    max_charge_kw       NUMERIC(6,2),
    max_export_kw       NUMERIC(6,2),

    -- Tariff context at scheduling time
    tariff_name         VARCHAR(60),            -- e.g. 'octopus_agile'
    expected_rate_pence_per_kwh NUMERIC(6,2),

    -- Outcome
    actual_energy_wh    INT,
    resulting_session_id UUID                   REFERENCES charging_sessions(id),

    -- AI agent that created this
    created_by_agent    BOOLEAN                 NOT NULL DEFAULT FALSE,
    agent_task_id       UUID,

    created_at          TIMESTAMPTZ             NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ             NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_grid_schedules_user   ON grid_schedules (user_id, window_start);
CREATE INDEX idx_grid_schedules_status ON grid_schedules (status, window_start) WHERE status = 'scheduled';

CREATE TRIGGER trg_grid_schedules_updated_at
    BEFORE UPDATE ON grid_schedules
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


