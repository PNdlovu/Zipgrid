-- ============================================================
-- MODULE O — ESG / CARBON DATA PRODUCTS
-- Per-session carbon data, cumulative platform metrics,
-- and subscription tiers for B2B ESG reporting.
-- ============================================================

CREATE TYPE esg_report_format AS ENUM (
    'csv',
    'json',
    'pdf'
);

CREATE TYPE esg_subscription_tier AS ENUM (
    'free',            -- rolling 30-day summary only
    'standard',        -- monthly export, 12-month history
    'premium'          -- API access, custom date range, multiple formats, CO2e certificates
);

-- Per-session carbon record (written by SessionService when session completes)
CREATE TABLE session_carbon_records (
    id              BIGSERIAL   PRIMARY KEY,
    session_id      UUID        NOT NULL REFERENCES charging_sessions(id) ON DELETE CASCADE,
    user_id         UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    -- Energy data (from charging_sessions.energy_consumed_wh)
    energy_wh       INT         NOT NULL,

    -- Grid carbon intensity at time of session (g CO2e/kWh)
    -- Pulled from National Grid ESO API (UK) or ENTSO-E (EU)
    grid_intensity_gco2_per_kwh NUMERIC(7, 2),

    -- Calculated CO2 saved vs petrol equivalent
    co2_saved_grams INT,        -- vs average UK petrol car at 120g CO2/km, 7.5L/100km
    km_equivalent   NUMERIC(8, 2),  -- km this charge could power

    -- Tree equivalent (for consumer-friendly display)
    tree_hours_equivalent NUMERIC(8, 2),

    -- Region at time of session
    region_code     VARCHAR(10),
    grid_provider   VARCHAR(50),

    recorded_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_carbon_records_session ON session_carbon_records (session_id);
CREATE INDEX idx_carbon_records_user    ON session_carbon_records (user_id, recorded_at DESC);
CREATE INDEX idx_carbon_records_region  ON session_carbon_records (region_code, recorded_at DESC);


-- Cumulative ESG totals per user (denormalised, updated by trigger)
CREATE TABLE user_esg_totals (
    user_id                 UUID        PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    total_energy_wh         BIGINT      NOT NULL DEFAULT 0,
    total_co2_saved_grams   BIGINT      NOT NULL DEFAULT 0,
    total_sessions          INT         NOT NULL DEFAULT 0,
    total_km_equivalent     NUMERIC(12, 2) NOT NULL DEFAULT 0,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- ESG report exports log (for B2B / fleet / SMB)
CREATE TABLE esg_report_exports (
    id              UUID                    PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id         UUID                    NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    fleet_account_id UUID                   REFERENCES fleet_accounts(id) ON DELETE SET NULL,

    format          esg_report_format       NOT NULL DEFAULT 'csv',
    tier            esg_subscription_tier   NOT NULL DEFAULT 'free',

    date_from       DATE                    NOT NULL,
    date_to         DATE                    NOT NULL,

    row_count       INT,
    file_url        TEXT,                   -- Railway / S3 pre-signed download URL
    expires_at      TIMESTAMPTZ,            -- download link expiry (24 hrs)

    created_at      TIMESTAMPTZ             NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_esg_exports_user  ON esg_report_exports (user_id, created_at DESC);
CREATE INDEX idx_esg_exports_fleet ON esg_report_exports (fleet_account_id) WHERE fleet_account_id IS NOT NULL;


-- Platform-wide ESG totals (single row, updated by pg_cron nightly)
CREATE TABLE platform_esg_totals (
    id                      INT             PRIMARY KEY DEFAULT 1,
    total_sessions          BIGINT          NOT NULL DEFAULT 0,
    total_energy_kwh        NUMERIC(14, 3)  NOT NULL DEFAULT 0,
    total_co2_saved_tonnes  NUMERIC(12, 4)  NOT NULL DEFAULT 0,
    total_km_equivalent     BIGINT          NOT NULL DEFAULT 0,
    unique_drivers          INT             NOT NULL DEFAULT 0,
    last_calculated_at      TIMESTAMPTZ     NOT NULL DEFAULT NOW(),

    CONSTRAINT platform_esg_singleton CHECK (id = 1)
);

INSERT INTO platform_esg_totals DEFAULT VALUES ON CONFLICT DO NOTHING;


