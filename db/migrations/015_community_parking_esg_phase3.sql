-- ============================================================
-- MODULE P — COMMUNITY HUB
-- AI-first EV community. Every post answered in < 3 seconds.
-- ============================================================

CREATE TYPE community_post_type AS ENUM (
    'question',        -- Ask & Answer Hub
    'tip',             -- tip / how-to
    'report',          -- fault / issue report (links to listing or area)
    'discussion',      -- open discussion
    'emergency_help',  -- SOS channel post
    'expert_insight'   -- installer / tariff expert contribution
);

CREATE TYPE community_post_status AS ENUM (
    'pending_moderation',  -- awaiting AI/human review
    'published',           -- live and visible
    'removed',             -- removed by moderation
    'locked'               -- no further replies allowed
);

CREATE TYPE community_reply_type AS ENUM (
    'ai_instant',          -- auto-generated by AI community agent
    'human',               -- written by platform user
    'expert'               -- from a verified expert (installer, advisor)
);

CREATE TYPE community_report_reason AS ENUM (
    'spam',
    'offensive',
    'misinformation',
    'off_topic',
    'other'
);


-- Community posts
CREATE TABLE community_posts (
    id              UUID                    PRIMARY KEY DEFAULT gen_random_uuid(),
    author_user_id  UUID                    NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    type            community_post_type     NOT NULL DEFAULT 'question',
    status          community_post_status   NOT NULL DEFAULT 'pending_moderation',

    title           VARCHAR(200)            NOT NULL,
    body            TEXT                    NOT NULL,

    -- Voice post: stores the original transcription
    is_voice_post   BOOLEAN                 NOT NULL DEFAULT FALSE,
    voice_audio_url TEXT,                    -- optional: store Whisper transcription source

    -- Tags / classification (added by AI at post time)
    tags            TEXT[]                  NOT NULL DEFAULT '{}',
    -- e.g. ['octopus_agile', 'zappi', 'london', 'billing']

    -- Listing/region association
    listing_id      UUID                    REFERENCES charger_listings(id) ON DELETE SET NULL,
    region_code     VARCHAR(10),            -- e.g. 'GB-LND', 'GB-MCR'

    -- Engagement
    view_count      INT                     NOT NULL DEFAULT 0,
    reply_count     INT                     NOT NULL DEFAULT 0,
    upvote_count    INT                     NOT NULL DEFAULT 0,
    is_answered     BOOLEAN                 NOT NULL DEFAULT FALSE, -- has an accepted/verified reply

    -- AI moderation verdict
    ai_moderation_score     NUMERIC(4,3),   -- 0.000–1.000 safety score
    ai_moderation_reason    TEXT,           -- why it was flagged or passed

    -- Pinning / featured
    is_pinned       BOOLEAN                 NOT NULL DEFAULT FALSE,
    pinned_by_user_id UUID                  REFERENCES users(id),

    created_at      TIMESTAMPTZ             NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ             NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_community_posts_author     ON community_posts (author_user_id, created_at DESC);
CREATE INDEX idx_community_posts_status     ON community_posts (status) WHERE status = 'published';
CREATE INDEX idx_community_posts_type       ON community_posts (type, created_at DESC);
CREATE INDEX idx_community_posts_tags       ON community_posts USING GIN (tags);
CREATE INDEX idx_community_posts_listing    ON community_posts (listing_id) WHERE listing_id IS NOT NULL;
CREATE INDEX idx_community_posts_region     ON community_posts (region_code) WHERE region_code IS NOT NULL;
CREATE INDEX idx_community_posts_unanswered ON community_posts (created_at DESC) WHERE is_answered = FALSE AND status = 'published';

CREATE TRIGGER trg_community_posts_updated_at
    BEFORE UPDATE ON community_posts
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


-- Community replies
CREATE TABLE community_replies (
    id              UUID                    PRIMARY KEY DEFAULT gen_random_uuid(),
    post_id         UUID                    NOT NULL REFERENCES community_posts(id) ON DELETE CASCADE,
    author_user_id  UUID                    REFERENCES users(id) ON DELETE SET NULL,   -- NULL for AI replies
    parent_reply_id UUID                    REFERENCES community_replies(id) ON DELETE CASCADE, -- nested replies

    type            community_reply_type    NOT NULL DEFAULT 'human',
    body            TEXT                    NOT NULL,

    -- For AI replies
    ai_model_used   VARCHAR(50),            -- e.g. 'gpt-4o'
    ai_confidence   NUMERIC(4,3),           -- 0.000–1.000

    -- For expert replies
    expert_credential VARCHAR(100),         -- e.g. 'OZEV Certified Installer', 'Tariff Adviser'

    -- Engagement
    upvote_count    INT                     NOT NULL DEFAULT 0,
    is_accepted     BOOLEAN                 NOT NULL DEFAULT FALSE,    -- marked by post author
    is_verified     BOOLEAN                 NOT NULL DEFAULT FALSE,    -- 3+ upvotes = community-verified

    is_removed      BOOLEAN                 NOT NULL DEFAULT FALSE,
    removal_reason  TEXT,

    created_at      TIMESTAMPTZ             NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ             NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_community_replies_post     ON community_replies (post_id, created_at ASC);
CREATE INDEX idx_community_replies_author   ON community_replies (author_user_id) WHERE author_user_id IS NOT NULL;
CREATE INDEX idx_community_replies_accepted ON community_replies (post_id) WHERE is_accepted = TRUE;

CREATE TRIGGER trg_community_replies_updated_at
    BEFORE UPDATE ON community_replies
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


-- Community votes (upvotes on posts and replies, one per user per item)
CREATE TABLE community_votes (
    id              BIGSERIAL   PRIMARY KEY,
    user_id         UUID        NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    post_id         UUID        REFERENCES community_posts(id) ON DELETE CASCADE,
    reply_id        UUID        REFERENCES community_replies(id) ON DELETE CASCADE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_vote_post  UNIQUE (user_id, post_id),
    CONSTRAINT uq_vote_reply UNIQUE (user_id, reply_id),
    CONSTRAINT chk_vote_target CHECK (
        (post_id IS NOT NULL AND reply_id IS NULL) OR
        (post_id IS NULL AND reply_id IS NOT NULL)
    )
);

CREATE INDEX idx_community_votes_post  ON community_votes (post_id)  WHERE post_id IS NOT NULL;
CREATE INDEX idx_community_votes_reply ON community_votes (reply_id) WHERE reply_id IS NOT NULL;


-- Community reports (abuse / misinformation flags)
CREATE TABLE community_reports (
    id              BIGSERIAL               PRIMARY KEY,
    reporter_user_id UUID                   NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    post_id         UUID                    REFERENCES community_posts(id) ON DELETE CASCADE,
    reply_id        UUID                    REFERENCES community_replies(id) ON DELETE CASCADE,
    reason          community_report_reason NOT NULL,
    detail          TEXT,
    resolved        BOOLEAN                 NOT NULL DEFAULT FALSE,
    resolved_by     UUID                    REFERENCES users(id),
    resolved_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ             NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_report_target CHECK (
        (post_id IS NOT NULL AND reply_id IS NULL) OR
        (post_id IS NULL AND reply_id IS NOT NULL)
    )
);

CREATE INDEX idx_community_reports_unresolved ON community_reports (created_at DESC) WHERE resolved = FALSE;


-- ============================================================
-- MODULE N — PARKING / NON-CHARGING P2P LISTINGS
-- Hosts can list parking bays without a charger.
-- Charges by the hour/day. Future: EV-priority parking.
-- ============================================================

CREATE TYPE parking_listing_status AS ENUM (
    'draft',
    'published',
    'paused',
    'archived'
);

CREATE TYPE parking_price_unit AS ENUM (
    'per_hour',
    'per_day',
    'per_session'     -- fixed price regardless of duration
);

CREATE TABLE parking_listings (
    id              UUID                        PRIMARY KEY DEFAULT gen_random_uuid(),
    host_profile_id UUID                        NOT NULL REFERENCES host_profiles(id) ON DELETE RESTRICT,

    -- Location (PostGIS)
    address_line1   VARCHAR(200)                NOT NULL,
    city            VARCHAR(100)                NOT NULL,
    postcode        VARCHAR(10)                 NOT NULL,
    latitude        NUMERIC(10, 7)              NOT NULL,
    longitude       NUMERIC(10, 7)              NOT NULL,

    -- Description
    title           VARCHAR(150)                NOT NULL,
    description     TEXT,

    -- Pricing (pence)
    price_pence     INT                         NOT NULL,
    price_unit      parking_price_unit          NOT NULL DEFAULT 'per_hour',
    min_duration_minutes INT                    NOT NULL DEFAULT 60,
    max_duration_hours   INT,

    -- Availability (same structure as charger_listings)
    available_from  TIME,
    available_to    TIME,
    available_days  SMALLINT[]                  DEFAULT '{1,2,3,4,5,6,0}', -- 0=Sunday ISO day

    -- Features
    is_ev_dedicated     BOOLEAN                 NOT NULL DEFAULT FALSE,
    has_cctv            BOOLEAN                 NOT NULL DEFAULT FALSE,
    is_covered          BOOLEAN                 NOT NULL DEFAULT FALSE,
    is_disabled_access  BOOLEAN                 NOT NULL DEFAULT FALSE,

    -- Status & stats
    status          parking_listing_status      NOT NULL DEFAULT 'draft',
    view_count      INT                         NOT NULL DEFAULT 0,
    booking_count   INT                         NOT NULL DEFAULT 0,
    average_rating  NUMERIC(3, 2)               DEFAULT NULL,
    review_count    INT                         NOT NULL DEFAULT 0,

    created_at      TIMESTAMPTZ                 NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ                 NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_parking_listings_location ON parking_listings (latitude, longitude);
CREATE INDEX idx_parking_listings_host     ON parking_listings (host_profile_id);
CREATE INDEX idx_parking_listings_status   ON parking_listings (status) WHERE status = 'published';
CREATE INDEX idx_parking_listings_city     ON parking_listings (city, status);

CREATE TRIGGER trg_parking_listings_updated_at
    BEFORE UPDATE ON parking_listings
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Parking bookings (simpler than charging — no OCPP, no session)
